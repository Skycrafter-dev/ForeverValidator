#!/usr/bin/env python3
"""Generates car_fields.inc (CarPack scalar X-macro) and curve_ids.inc from
src/twin/model/stadiumcar-values.json. Run from the repo root:
    python3 src/twin/model/gen_car_fields.py src/twin/model/stadiumcar-values.json src/twin/model
The output is checked in; rerun only when the JSON's field set changes."""
import json, re, sys

src, outdir = sys.argv[1], sys.argv[2]
values = json.load(open(src))['values']

CTYPE = {'f32': 'F32', 'u32': 'U32', 'i32': 'I32', 'bool': 'BOOL'}
STRUCTURED = ('tuning.curves.', 'tuning.gearedDrive.transmission.gearSpeedRatio', 'tuning.gearedDrive.transmission.upshiftThreshold',
              'tuning.gearedDrive.transmission.downshiftThreshold', 'tuning.gearedDrive.transmission.rpmWanted',
              'tuning.gearedDrive.transmission.targetInputBias', 'tuning.gearedDrive.transmission.rpmDelta')
scalars = []
for path, v in values.items():
    if path.startswith('default.'):
        continue
    top = path.startswith('tuning.') or path.startswith('vehicle.initialParameters.') or path.startswith('derived.dyna.') \
        or path in ('derived.wheelSet.present', 'derived.wheelSet.restDamperAbsorb')
    if not top or path.startswith(STRUCTURED):
        continue
    if v['type'] not in CTYPE:
        raise SystemExit('unexpected type %s for %s' % (v['type'], path))
    name = path
    for p in ('tuning.', 'vehicle.', 'derived.'):
        if name.startswith(p):
            name = name[len(p):] if p == 'tuning.' else p[:-1] + '_' + name[len(p):]
            break
    name = re.sub(r'[^A-Za-z0-9]', '_', name)
    scalars.append((name, CTYPE[v['type']], path))

with open(outdir + '/car_fields.inc', 'w') as f:
    f.write('// GENERATED by gen_car_fields.py from src/twin/model/stadiumcar-values.json. Do not edit.\n')
    f.write('// TW_CAR(member, type, "json path"): every StadiumCar scalar the pack carries, bit-exact.\n')
    for name, t, path in scalars:
        f.write('TW_CAR(%s, %s, "%s")\n' % (name, t, path))

curves = sorted({m.group(1) for p in values for m in [re.match(r'tuning\.curves\.([A-Za-z0-9]+)\.', p)] if m})
with open(outdir + '/curve_ids.inc', 'w') as f:
    f.write('// GENERATED by gen_car_fields.py. TW_CURVE(name, "json name")\n')
    for c in curves:
        f.write('TW_CURVE(%s, "%s")\n' % (c, c))
print('scalars', len(scalars), 'curves', len(curves))
